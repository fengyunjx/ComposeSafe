// Postgres keeps its cluster in PGDATA. Up to version 17 the images use
// /var/lib/postgresql/data and declare it a VOLUME; from 18 on PGDATA is
// /var/lib/postgresql/<major>/docker and the VOLUME is /var/lib/postgresql.
const (
	pgDataLegacy = "/var/lib/postgresql/data"
	pgDataParent = "/var/lib/postgresql"
)

// pgMove is where the data of a Postgres service goes during a major upgrade.
type pgMove struct {
	Service   string
	Type      string // volume | bind
	Old       string // docker volume name or host directory in use now
	New       string // docker volume name or host directory to create
	Target    string // mount point now
	NewTarget string // mount point after; "" when unchanged
	Suffix    string // "_pg16": appended to the compose key / path
	Writers   []string
}

func (m *pgMove) ref() snapshot.RestoredMount {
	return snapshot.RestoredMount{Service: m.Service, Type: m.Type, Old: m.Old, New: m.New}
}

// planPGMove finds the data mount of a Postgres service and decides the new
// location. The old one is never written to by the new version.
func planPGMove(proj *compose.Project, svc *compose.Service, to compose.ImageRef) (*pgMove, error) {
	if to.Version == nil {
		return nil, fmt.Errorf("cannot read a Postgres version from the target %q", to.Raw)
	}
	major := to.Version.Major
	var mount *compose.Mount
	for i := range svc.Mounts {
		m := &svc.Mounts[i]
		if m.ReadOnly || (m.Type != "volume" && m.Type != "bind") {
			continue
		}
		if m.Target == pgDataLegacy || m.Target == pgDataParent {
			mount = m
			break
		}
	}
	if mount == nil || (mount.Type == "volume" && mount.Source == "") {
		return nil, fmt.Errorf("%s keeps its data in neither a named volume nor a bind directory at %s, so the data cannot be moved to a new volume: put it in a named volume first",
			svc.Name, pgDataLegacy)
	}
	mv := &pgMove{Service: svc.Name, Type: mount.Type, Target: mount.Target, Suffix: "_pg" + strconv.Itoa(major)}
	if major >= 18 && mount.Target == pgDataLegacy {
		mv.NewTarget = pgDataParent
	}
	if mount.Type == "bind" {
		mv.Old = mount.Source
		mv.New = strings.TrimRight(mount.Source, "/") + mv.Suffix
	} else {
		mv.Old = mount.VolumeName
		mv.New = mount.VolumeName + mv.Suffix
	}
	mv.Writers = dependents(proj, []string{svc.Name})
	return mv, nil
}

// checkFree refuses a destination that already exists: reusing it could mix
// two clusters.
func (m *pgMove) checkFree(ctx context.Context, r docker.Runner) error {
	if m.Type == "bind" {
		ents, err := os.ReadDir(m.New)
		switch {
		case errors.Is(err, os.ErrNotExist):
			return nil
		case err != nil:
			return err
		case len(ents) > 0:
			return fmt.Errorf("%s already exists and is not empty: refusing to restore into it", m.New)
		}
		return nil
	}
	res, _ := r.Run(ctx, []string{"volume", "inspect", m.New}, docker.Opts{})
	if strings.Contains(string(res.Stdout), `"Name"`) {
		return fmt.Errorf("volume %s already exists: refusing to restore into it", m.New)
	}
	return nil
}

func (m *pgMove) create(ctx context.Context, r docker.Runner, runID string) error {
	if err := m.checkFree(ctx, r); err != nil {
		return err
	}
	if m.Type == "bind" {
		return os.MkdirAll(m.New, 0o755)
	}
	_, err := r.Run(ctx, []string{"volume", "create", "--label", "composesafe.upgrade=" + runID, m.New}, docker.Opts{})
	return err
}

// pgMoveEdits adds the compose edit that points the service at the new data
// location (and, for Postgres 18, the new mount point).
func pgMoveEdits(files []string, edits []compose.FileEdit, mv *pgMove) ([]compose.FileEdit, error) {
	return moveMountEdit(files, edits, mv.Service, mv.Target, mv.NewTarget, mv.Suffix, mv.New)
}

// pgOverride makes the first start of the new server initialise only the
// default "postgres" database. The dump creates the application's database
// itself, and would fail on one the entrypoint already made.
const pgOverride = "# generated by composesafe: initialise an empty cluster; the dump creates the databases\nservices:\n  %s:\n    environment:\n      POSTGRES_DB: postgres\n"

// migrate replaces the old cluster by a new one of the target major version:
// stop the writers, take a final dump, start the new server on an empty
// volume, restore, ANALYZE and compare. The old volume is never touched.
// The compose files already point at the new volume when this runs.
func (u *upRun) migrate(ctx context.Context) error {
	rd := u.d.Run
	name := u.svc.Name
	sc := u.cfg.Service(name)
	timeout := intSeconds(sc.HealthTimeout)

	// 1. Writers stop first so that nothing is written after the final dump.
	if err := u.step("upgrade.quiesce", func() error {
		var stop []string
		for _, w := range u.move.Writers {
			up, err := u.cc.Running(ctx, rd.Runner, w)
			if err != nil {
				return err
			}
			if up {
				stop = append(stop, w)
			}
		}
		u.m.Upgrade.Stopped = stop // recorded first: a rollback starts them again
		if err := u.m.Save(u.dir); err != nil {
			return err
		}
		if len(stop) == 0 {
			return nil
		}
		rd.Progress("up.pg.quiesce", strings.Join(stop, ", "))
		_, err := u.cc.Run(ctx, rd.Runner, docker.Opts{}, append([]string{"stop"}, stop...)...)
		return err
	}); err != nil {
		return err
	}

	// 2. The final dump, from the old server.
	ex := composeExec(u.cc, rd.Runner, name)
	var user string
	var before map[string]int
	dumpRel := sanitizeFile(name) + ".upgrade.sql.gz"
	if err := u.step("upgrade.dump", func() error {
		var err error
		if user, err = pg.ServerUser(ctx, ex); err != nil {
			return err
		}
		if before, err = pg.TableCounts(ctx, ex, user, sc.PGPasswordEnv); err != nil {
			return err
		}
		rd.Progress("up.pg.dump", name)
		out, err := pg.Dump(ctx, ex, user, sc.PGPasswordEnv, filepath.Join(u.dir, dumpRel))
		if err != nil {
			return err
		}
		a := snapshot.Artifact{Kind: snapshot.KindPGUpgradeDump, Service: name, Path: dumpRel,
			SHA256: out.SHA256, Size: out.Size, RawSize: out.RawSize}
		if res := snapshot.Verify(u.dir, &snapshot.Manifest{Artifacts: []snapshot.Artifact{a}}); !res.OK() {
			return fmt.Errorf("the final dump is not usable: %s", res.Problems[0])
		}
		u.m.Artifacts = append(u.m.Artifacts, a)
		return u.m.Save(u.dir)
	}); err != nil {
		return err
	}

	// 3. The new server, on an empty volume.
	overridePath := filepath.Join(u.dir, "pgmajor-override.yml")
	cc := u.cc
	cc.Files = append(append([]string(nil), u.cc.Files...), overridePath)
	if err := u.step("upgrade.init", func() error {
		if err := os.WriteFile(overridePath, []byte(fmt.Sprintf(pgOverride, name)), 0o600); err != nil {
			return err
		}
		rd.Progress("up.pg.init", name, u.p.To.Raw)
		if _, err := cc.Run(ctx, rd.Runner, docker.Opts{}, "up", "-d", "--no-deps", "--wait", "--wait-timeout", timeout, name); err != nil {
			return err
		}
		// The entrypoint first runs a throwaway server on the socket only; TCP
		// answers once the real one is up.
		return waitTCP(ctx, composeExec(cc, rd.Runner, name), user, 120, rd.Sleep)
	}); err != nil {
		return err
	}

	// 4. Restore, refresh statistics, compare.
	nx := composeExec(cc, rd.Runner, name)
	if err := u.step("upgrade.restore", func() error {
		rd.Progress("up.pg.restore", name)
		errsFound, err := pg.Restore(ctx, nx, user, sc.PGPasswordEnv, filepath.Join(u.dir, dumpRel))
		if err != nil {
			return err
		}
		if len(errsFound) > 0 {
			return fmt.Errorf("restoring into the new server reported %d error(s), first: %s", len(errsFound), errsFound[0])
		}
		return nil
	}); err != nil {
		return err
	}
	if err := u.step("upgrade.analyze", func() error {
		rd.Progress("up.pg.analyze", name)
		return pg.Analyze(ctx, nx, user, sc.PGPasswordEnv)
	}); err != nil {
		return err
	}
	if err := u.step("upgrade.compare", func() error {
		after, err := pg.TableCounts(ctx, nx, user, sc.PGPasswordEnv)
		if err != nil {
			return err
		}
		if d := pg.CompareTables(before, after); d != "" {
			return errors.New(d)
		}
		return nil
	}); err != nil {
		return err
	}

	// 5. Recreate the container from the user's own compose files, without the
	// first-start override.
	return u.step("upgrade.up", func() error {
		rd.Progress("up.up", name)
		if _, err := u.cc.Run(ctx, rd.Runner, docker.Opts{}, "up", "-d", "--no-deps", "--wait", "--wait-timeout", timeout, name); err != nil {
			return err
		}
		return pg.WaitReady(ctx, composeExec(u.cc, rd.Runner, name), user, 90, time.Second, rd.Sleep)
	})
}

// startWriters brings back the services the migration stopped and verifies
// each of them.
func (u *upRun) startWriters(ctx context.Context) error {
	stopped := u.m.Upgrade.Stopped
	if len(stopped) == 0 {
		return nil
	}
	rd := u.d.Run
	return u.step("upgrade.writers", func() error {
		rd.Progress("up.pg.writers", strings.Join(stopped, ", "))
		timeout := intSeconds(u.cfg.Service(u.svc.Name).HealthTimeout)
		args := append([]string{"up", "-d", "--no-deps", "--wait", "--wait-timeout", timeout}, stopped...)
		if _, err := u.cc.Run(ctx, rd.Runner, docker.Opts{}, args...); err != nil {
			return err
		}
		for _, w := range stopped {
			v := verifyService(ctx, rd, u.cfg, u.cc, u.proj, w)
			u.res.Verify.Smoke = append(u.res.Verify.Smoke, v.Smoke...)
			if !v.OK() {
				return fmt.Errorf("%s: %s", w, v.Failure())
			}
		}
		return nil
	})
}
