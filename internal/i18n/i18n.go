// Package i18n holds the user-visible strings: two plain tables (English is
// the default, Chinese via `lang: zh`). No framework; add a key to both.
package i18n

import "fmt"

// T returns the translator for lang. Unknown keys return the key itself so a
// missing translation is visible rather than blank.
func T(lang string) func(key string, args ...any) string {
	table := en
	if lang == "zh" {
		table = zh
	}
	return func(key string, args ...any) string {
		s, ok := table[key]
		if !ok {
			if s, ok = en[key]; !ok {
				return key
			}
		}
		if len(args) == 0 {
			return s
		}
		return fmt.Sprintf(s, args...)
	}
}

